//! Compiler-authored native error messages and admitted source diagnostics.
//!
//! Catalog constants are the only admission for compiler-authored text. The
//! same rows drive pool interning and every static throw. Source diagnostics
//! instead carry their actual IR/prepared-unit authority: only StringPool can
//! mint a pooled handle after validating its projected diagnostic text was
//! collected in this pool. This does not prove Rust identity of the IR owner.

use super::*;
use std::borrow::Cow;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct RuntimeErrorMessage(RuntimeErrorMessageValue);

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum RuntimeErrorMessageValue {
    Catalog(&'static str),
    CollectedSource(i64),
}

macro_rules! runtime_error_message_catalog {
    ($($name:ident => $text:literal),+ $(,)?) => {
        impl RuntimeErrorMessage {
            $(pub(crate) const $name: Self = Self(RuntimeErrorMessageValue::Catalog($text));)+
            pub(crate) const CATALOG: &'static [Self] = &[$(Self::$name),+];
        }
    };
}

