impl RuntimeErrorMessage {
    pub(crate) const fn catalog_text(self) -> Option<&'static str> {
        match self.0 {
            RuntimeErrorMessageValue::Catalog(text) => Some(text),
            RuntimeErrorMessageValue::CollectedSource(_) => None,
        }
    }
}

/// These owners define all source-dependent compiler-thrown messages. There is
/// no String/&str variant: a caller cannot admit arbitrary uncollected text.
#[derive(Clone, Copy)]
pub(crate) enum SourceRuntimeErrorMessage<'a> {
    Expression(&'a TypedExpr),
    RegExp(&'a StaticRegExpCompilation),
    PreparedScript(&'a PreparedScriptOutcome),
    PreparedFunction(&'a scriptw_ir::PreparedDynamicFunctionOutcome),
    IdentifierWrite(scriptw_ir::IdentifierWriteErrorIr),
}

impl<'a> SourceRuntimeErrorMessage<'a> {
    fn text(self) -> Option<Cow<'a, str>> {
        match self {
            Self::Expression(expression) => match &expression.expr {
                ExprIr::RuntimeThrow { message, .. } => Some(Cow::Borrowed(message)),
                ExprIr::AssertSameValue { message, .. } => Some(Cow::Borrowed(message)),
                _ => None,
            },
            Self::RegExp(compilation) => match compilation {
                StaticRegExpCompilation::InvalidSyntax { message } => Some(Cow::Borrowed(message)),
                StaticRegExpCompilation::Program(_) => None,
            },
            Self::PreparedScript(outcome) => match outcome {
                PreparedScriptOutcome::DeferredSyntaxError { message } => {
                    Some(Cow::Borrowed(message))
                }
                PreparedScriptOutcome::Executable(_) => None,
            },
            Self::PreparedFunction(outcome) => match outcome {
                scriptw_ir::PreparedDynamicFunctionOutcome::SyntaxError { message } => {
                    Some(Cow::Borrowed(message))
                }
                scriptw_ir::PreparedDynamicFunctionOutcome::Compiled { .. } => None,
            },
            Self::IdentifierWrite(error) => Some(Cow::Borrowed(error.message())),
        }
    }
}

impl StringPool {
    pub(super) fn intern_source_runtime_error_message(
        &mut self,
        source: SourceRuntimeErrorMessage<'_>,
    ) {
        let Some(text) = source.text() else {
            return;
        };
        self.intern_string(&text);
        let payload = self.payload(&text);
        self.source_runtime_error_messages
            .insert(text.into_owned(), payload);
    }

    /// Validate a source-owned diagnostic once, while the pool is immutable.
    /// Source handles validate diagnostic text membership in this pool;
    /// unlike static catalog constants they are not portable between pools.
    pub(crate) fn source_runtime_error_message(
        &self,
        source: SourceRuntimeErrorMessage<'_>,
    ) -> Result<RuntimeErrorMessage, EmitError> {
        let text = source.text().ok_or_else(|| {
            EmitError::unsupported("runtime error source does not carry an error message")
        })?;
        let payload = self
            .source_runtime_error_messages
            .get(text.as_ref())
            .copied()
            .ok_or_else(|| {
                EmitError::unsupported(format!(
                    "runtime error source message was not collected in this module: `{text}`"
                ))
            })?;
        Ok(RuntimeErrorMessage(
            RuntimeErrorMessageValue::CollectedSource(payload),
        ))
    }

    pub(crate) fn runtime_error_payload(&self, message: RuntimeErrorMessage) -> i64 {
        match message.0 {
            RuntimeErrorMessageValue::Catalog(text) => self.payload(text),
            RuntimeErrorMessageValue::CollectedSource(payload) => payload,
        }
    }

    pub(super) fn intern_runtime_error_catalog(&mut self) {
        for message in RuntimeErrorMessage::CATALOG {
            // CATALOG is generated solely from the literal rows above.
            if let RuntimeErrorMessageValue::Catalog(text) = message.0 {
                self.intern_string(text);
            }
        }
    }
}

