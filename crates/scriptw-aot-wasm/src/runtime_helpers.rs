/// Maximum bytes for one RegExp matcher's transient choice-frame arena.
///
/// The caller capture output, live capture/repeat state and all retained choice
/// frames share this ceiling. A single checked tail owner starts with one frame
/// and grows capacity only for actual backtracking demand after immutable input
/// materialization. Numeric repetition bounds never size an allocation. Admission
/// and failed memory growth report ResourceExhausted (RangeError) before writes;
/// the arena is scrubbed and rewound before an observable matcher exit.
pub(crate) const REGEXP_MATCHER_SCRATCH_MAX_BYTES: i64 = 512 * 1024 * 1024;

/// How a failed RegExp matcher result becomes a JavaScript throw.
///
/// Corrupt generated bytecode is an internal engine failure and preserves the
/// existing generic `Error`. Exhausting the explicitly allocated matcher arena
/// is a resource failure and therefore uses the current function realm's
/// `RangeError`. Keeping this as a closed domain makes a third route an
/// exhaustive-match update at the sole consumer rather than a boolean policy.
pub(crate) enum RegExpMatcherFailureRoute {
    GenericError,
    CurrentFunctionRealmRangeError,
}

/// Declares the complete RegExp matcher status ABI from one failure-row source.
///
/// Each row must choose its wire word, JavaScript error route and stable
/// message. The macro derives both `ALL` views and every projection, so adding
/// a failure cannot leave the helper writer, dynamic result router or string
/// pool on an old parallel list.
macro_rules! regexp_matcher_status_domain {
    (
        $(
            $failure:ident => {
                word: $word:literal,
                route: $route:ident,
                message: $message:ident,
            }
        ),+ $(,)?
    ) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub(crate) enum RegExpMatcherFailure {
            $( $failure, )+
        }

        impl RegExpMatcherFailure {
            pub(crate) const ALL: &'static [Self] = &[
                $( Self::$failure, )+
            ];

            pub(crate) const fn abi_word(self) -> i64 {
                match self {
                    $( Self::$failure => $word, )+
                }
            }

            pub(crate) const fn route(self) -> RegExpMatcherFailureRoute {
                match self {
                    $( Self::$failure => RegExpMatcherFailureRoute::$route, )+
                }
            }

            pub(crate) const fn message(self) -> RuntimeErrorMessage {
                match self {
                    $( Self::$failure => RuntimeErrorMessage::$message, )+
                }
            }
        }

        /// The four-result matcher's final result slot.
        ///
        /// `Complete` covers both match and no-match; the first result slot
        /// distinguishes those normal outcomes. Every failure retains its
        /// typed reason until the observable wrapper has rewound transient
        /// scratch storage and is ready to throw.
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub(crate) enum RegExpMatcherStatus {
            Complete,
            Failed(RegExpMatcherFailure),
        }

        impl RegExpMatcherStatus {
            pub(crate) const ALL: &'static [Self] = &[
                Self::Complete,
                $( Self::Failed(RegExpMatcherFailure::$failure), )+
            ];

            pub(crate) const fn abi_word(self) -> i64 {
                match self {
                    Self::Complete => 0,
                    Self::Failed(failure) => failure.abi_word(),
                }
            }
        }
    };
}

regexp_matcher_status_domain! {
    CorruptProgram => {
        word: 1,
        route: GenericError,
        message: REGEXP_COMPILED_PROGRAM_MATCHER_FAILED,
    },
    ResourceExhausted => {
        word: 2,
        route: CurrentFunctionRealmRangeError,
        message: REGEXP_MATCHER_SCRATCH_ARENA_EXCEEDS_THE_ENGINE_ADDRESSABLE_RESOURCE_LIMIT,
    },
}

const fn regexp_matcher_status_words_are_unique() -> bool {
    let mut left = 0;
    while left < RegExpMatcherStatus::ALL.len() {
        let mut right = left + 1;
        while right < RegExpMatcherStatus::ALL.len() {
            if RegExpMatcherStatus::ALL[left].abi_word()
                == RegExpMatcherStatus::ALL[right].abi_word()
            {
                return false;
            }
            right += 1;
        }
        left += 1;
    }
    true
}

const _: () = assert!(
    regexp_matcher_status_words_are_unique(),
    "RegExp matcher statuses must have unique ABI words"
);

/// The pure Pattern compiler's private second result slot. These are not
/// JavaScript completion tags. Syntax/resource/internal failures retain
/// JavaScript errors.
/// No non-success result publishes receiver state.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum RegExpCompilerStatus {
    Compiled,
    SyntaxError,
    ResourceExhausted,
    CorruptProgram,
}
impl RegExpCompilerStatus {
    pub(crate) const ALL: [Self; 4] = [
        Self::Compiled,
        Self::SyntaxError,
        Self::ResourceExhausted,
        Self::CorruptProgram,
    ];
    pub(crate) const fn abi_word(self) -> i64 {
        match self {
            Self::Compiled => 0,
            Self::SyntaxError => 1,
            Self::ResourceExhausted => 3,
            Self::CorruptProgram => 4,
        }
    }
}

/// One fact a module can carry about itself that some *conditional* runtime
/// helper's emission depends on.
///
/// Closed set, and the only way to put a fact into a [`RuntimeHelperEmission`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u32)]
pub(crate) enum RuntimeHelperFact {
    UsesJsonStringify = 0,
}

impl RuntimeHelperFact {
    const fn bit(self) -> u32 {
        1u32 << (self as u32)
    }
}

/// The facts a module knows about itself that decide whether a *conditional*
/// runtime helper is emitted at all.
///
/// Passed by value into [`RuntimeHelperId::is_emitted`] so that the emission
/// condition of every helper is stated in exactly one place, next to its type
/// index, rather than being spread over an `if` in the function section and a
/// matching `if let Some(..)` in the code section.
///
/// A *set* of [`RuntimeHelperFact`]s rather than a struct of `bool` fields,
/// because [`Self::NONE`] has to mean "no fact holds" by construction. As a
/// struct literal it was a hand-written list that whoever added the second
/// conditional helper would also have had to remember to extend with `false`;
/// writing `true` there instead compiles, makes [`RuntimeHelperId::is_conditional`]
/// answer `false` for a genuinely conditional helper, and silently defeats
/// [`RuntimeHelperId::conditional_helpers_are_last`] — handing out shifted
/// function indices with both `const` assertions still green. The empty set
/// cannot be written wrong.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct RuntimeHelperEmission(u32);

impl RuntimeHelperEmission {
    /// The emission context in which every conditional helper is absent. Used
    /// by [`RuntimeHelperId::is_conditional`] so "conditional" is derived from
    /// `is_emitted` instead of being a second, separately-maintained match.
    pub(crate) const NONE: Self = Self(0);

    /// Adds `fact` to the set when `holds`. The only constructor beyond
    /// [`Self::NONE`], so every emission context is built up from the empty one.
    pub(crate) const fn with(self, fact: RuntimeHelperFact, holds: bool) -> Self {
        if holds {
            Self(self.0 | fact.bit())
        } else {
            self
        }
    }

    pub(crate) const fn holds(self, fact: RuntimeHelperFact) -> bool {
        self.0 & fact.bit() != 0
    }
}

