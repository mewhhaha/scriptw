    const fn conditional_helpers_are_last() -> bool {
        let mut index = 0;
        let mut omitted = false;
        while index < Self::ALL.len() {
            if Self::ALL[index].is_conditional() {
                omitted = true;
            } else if omitted {
                return false;
            }
            index += 1;
        }
        true
    }
