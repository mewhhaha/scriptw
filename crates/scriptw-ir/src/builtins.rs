macro_rules! catalog_install_global {
    ($globals:ident, $occupied:ident, $count:expr, $variant:expr) => {};
    ($globals:ident, $occupied:ident, $count:expr, $variant:expr, $ordinal:expr) => {{
        let ordinal: GlobalOrdinal = $ordinal;
        let index = ordinal.index();
        if index >= $count {
            panic!("standard builtin global ordinal out of range");
        }
        if $occupied[index] {
            panic!("duplicate standard builtin global ordinal");
        }
        $occupied[index] = true;
        $globals[index] = $variant;
    }};
}

macro_rules! standard_builtin_catalog {
    (
        $(
            $variant:ident {
                function: $function_ordinal:expr => $function_id:tt,
                $(global: $global_ordinal:expr,)?
                $(global_name: $global_name:expr,)?
                debug: $debug_name:expr,
                flags: [$($flag:ident),* $(,)?],
                installer: $installer:ident,
                $(string: $string_name:expr,)?
                $(native: $native_name:expr,)?
            }
        )+
    ) => {
        #[repr(u16)]
        #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
        pub enum StandardBuiltinId {
            $($variant,)+
        }

        impl StandardBuiltinId {
            const FUNCTION_COUNT: usize = catalog_len!($($variant),+);
            const GLOBAL_COUNT: usize = 0 $(+ catalog_optional_count!($($global_ordinal)?))+;
            const DECLARATION_ORDER: [Self; Self::FUNCTION_COUNT] = [$(Self::$variant,)+];
            const FUNCTION_IDS: [&'static str; Self::FUNCTION_COUNT] = [$($function_id,)+];

            const FUNCTIONS: [Self; Self::FUNCTION_COUNT] = {
                let mut functions = [Self::DECLARATION_ORDER[0]; Self::FUNCTION_COUNT];
                let mut occupied = [false; Self::FUNCTION_COUNT];
                $(
                    {
                        let ordinal: FunctionOrdinal = $function_ordinal;
                        let index = ordinal.index();
                        if index >= Self::FUNCTION_COUNT {
                            panic!("standard builtin function ordinal out of range");
                        }
                        if occupied[index] {
                            panic!("duplicate standard builtin function ordinal");
                        }
                        occupied[index] = true;
                        functions[index] = Self::$variant;
                    }
                )+

                let mut i = 0;
                while i < occupied.len() {
                    if !occupied[i] {
                        panic!("missing standard builtin function ordinal");
                    }
                    i += 1;
                }
                functions
            };

            const GLOBALS: [Self; Self::GLOBAL_COUNT] = {
                let mut globals = [Self::DECLARATION_ORDER[0]; Self::GLOBAL_COUNT];
                let mut occupied = [false; Self::GLOBAL_COUNT];
                $(
                    catalog_install_global!(
                        globals,
                        occupied,
                        Self::GLOBAL_COUNT,
                        Self::$variant
                        $(, $global_ordinal)?
                    );
                )+

                let mut i = 0;
                while i < occupied.len() {
                    if !occupied[i] {
                        panic!("missing standard builtin global ordinal");
                    }
                    i += 1;
                }
                globals
            };

            const fn validate_catalog() {
                let mut i = 0;
                while i < Self::DECLARATION_ORDER.len() {
                    if Self::DECLARATION_ORDER[i] as usize != i {
                        panic!("standard builtin declaration order drifted");
                    }
                    i += 1;
                }
                assert_unique_function_ids(&Self::FUNCTION_IDS);
                let _ = Self::FUNCTIONS;
                let _ = Self::GLOBALS;
            }

            pub const fn global_name(self) -> Option<&'static str> {
                match self {
                    $(Self::$variant => catalog_optional!($($global_name)?),)+
                }
            }

            pub const fn debug_name(self) -> &'static str {
                match self {
                    $(Self::$variant => $debug_name,)+
                }
            }

            pub fn function_id(self) -> FunctionId {
                match self {
                    $(Self::$variant => $function_id.to_string(),)+
                }
            }

            pub fn from_function_id(function_id: &str) -> Option<Self> {
                match function_id {
                    $($function_id => Some(Self::$variant),)+
                    _ => None,
                }
            }

            pub const fn all_globals() -> &'static [Self] {
                &Self::GLOBALS
            }

            pub const fn all_functions() -> &'static [Self] {
                &Self::FUNCTIONS
            }

            /// Builtins whose body reads the host wall clock. The backend derives the
            /// `scriptw_host.wall_clock_millis` import (and therefore every later import
            /// index) from this, so a new clock reader must be flagged here or its
            /// emitter has no import to call.
            pub const fn requires_wall_clock(self) -> bool {
                self.flags().contains(BuiltinFlags::WALL_CLOCK)
            }

            /// Bodies that consume the Realm's admitted system time zone need
            /// the `scriptw_host.system_time_zone` import before code emission.
            pub const fn requires_system_time_zone(self) -> bool {
                self.flags().contains(BuiltinFlags::SYSTEM_TIME_ZONE)
            }

            pub const fn constructable(self) -> bool {
                self.flags().contains(BuiltinFlags::CONSTRUCTABLE)
            }

            pub const fn is_error_constructor(self) -> bool {
                self.flags().contains(BuiltinFlags::ERROR_CONSTRUCTOR)
            }

            pub const fn is_static_method(self) -> bool {
                self.flags().contains(BuiltinFlags::STATIC_METHOD)
            }

            pub const fn is_boxed_primitive_constructor(self) -> bool {
                self.flags().contains(BuiltinFlags::BOXED_PRIMITIVE)
            }

            pub const fn may_run_user_code_synchronously(self) -> bool {
                self.flags().contains(BuiltinFlags::SYNCHRONOUS_USER_CODE)
            }

            pub const fn always_throws(self) -> bool {
                self.flags().contains(BuiltinFlags::ALWAYS_THROWS)
            }

            pub(crate) const fn mutates_indexed_receiver(self) -> bool {
                self.flags()
                    .contains(BuiltinFlags::INDEXED_RECEIVER_MUTATION)
            }

            pub const fn intrinsic_installer(self) -> StandardBuiltinInstaller {
                match self {
                    $(Self::$variant => StandardBuiltinInstaller::$installer,)+
                }
            }

            const fn flags(self) -> BuiltinFlags {
                match self {
                    $(Self::$variant => catalog_flags!($($flag),*),)+
                }
            }

            pub const fn string_prototype_method_name(self) -> Option<&'static str> {
                match self {
                    $(Self::$variant => catalog_optional!($($string_name)?),)+
                }
            }

            pub const fn native_function_name(self) -> Option<&'static str> {
                match self {
                    $(Self::$variant => catalog_optional!($($native_name)?),)+
                }
            }
        }

        const _: () = StandardBuiltinId::validate_catalog();
    };
}

