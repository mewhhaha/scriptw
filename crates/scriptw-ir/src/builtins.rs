#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct BuiltinFlags(u16);

impl BuiltinFlags {
    const NONE: Self = Self(0);
    const WALL_CLOCK: u16 = 1 << 0;
    const CONSTRUCTABLE: u16 = 1 << 1;
    const ERROR_CONSTRUCTOR: u16 = 1 << 2;
    const STATIC_METHOD: u16 = 1 << 3;
    const BOXED_PRIMITIVE: u16 = 1 << 4;
    const RANDOM: u16 = 1 << 5;
    const SYNCHRONOUS_USER_CODE: u16 = 1 << 6;
    const ALWAYS_THROWS: u16 = 1 << 7;
    const INDEXED_RECEIVER_MUTATION: u16 = 1 << 8;
    const INTL_HOST: u16 = 1 << 9;
    const SYSTEM_TIME_ZONE: u16 = 1 << 10;

    const fn contains(self, flag: u16) -> bool {
        self.0 & flag != 0
    }
}

const fn catalog_str_eq(left: &str, right: &str) -> bool {
    let left = left.as_bytes();
    let right = right.as_bytes();
    if left.len() != right.len() {
        return false;
    }

    let mut i = 0;
    while i < left.len() {
        if left[i] != right[i] {
            return false;
        }
        i += 1;
    }
    true
}

const fn catalog_str_hash(value: &str) -> usize {
    let bytes = value.as_bytes();
    let mut hash = 0xcbf2_9ce4_8422_2325_u64;
    let mut i = 0;
    while i < bytes.len() {
        hash ^= bytes[i] as u64;
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
        i += 1;
    }
    hash as usize
}

const fn assert_unique_function_ids(ids: &[&str]) {
    // Keep the load factor below one half so this compile-time open-addressed
    // set stays linear in the size of the catalog. Growing past this capacity
    // is an intentional edit, not an invitation to fall back to an O(n^2)
    // duplicate scan on every `cargo check`.
    const TABLE_SIZE: usize = 4096;
    if ids.len() * 2 > TABLE_SIZE {
        panic!("standard builtin function ID table capacity exceeded");
    }

    let mut slots = [usize::MAX; TABLE_SIZE];
    let mut i = 0;
    while i < ids.len() {
        let mut slot = catalog_str_hash(ids[i]) % TABLE_SIZE;
        loop {
            let previous = slots[slot];
            if previous == usize::MAX {
                slots[slot] = i;
                break;
            }
            if catalog_str_eq(ids[i], ids[previous]) {
                panic!("duplicate standard builtin function ID");
            }
            slot = (slot + 1) % TABLE_SIZE;
        }
        i += 1;
    }
}

